<?php

namespace App\Domains\Commerce\Actions\Definitions;

use App\Domains\Commerce\Actions\Gateway\ShopifyGateway;
use App\Domains\Commerce\Actions\Models\ActionSettings;
use App\Domains\Commerce\Actions\OrderState;
use App\Domains\Commerce\Actions\OrderStateLoader;
use App\Domains\Commerce\Actions\Support\Money;
use Illuminate\Support\Str;

/**
 * A single-use discount code from an admin-approved template
 * (agent_action_settings.discount_templates): percentage or fixed, capped,
 * expiring, usageLimit 1, optionally limited to this customer.
 * discountCodeBasicCreate; scope write_discounts.
 *
 * The code is generated by the system (never by the model) when the action
 * is proposed, so the draft can quote it; it only works once the action has
 * succeeded and the reply waits for that.
 */
class DiscountCode extends ActionDefinition
{
    public const MUTATION = <<<'GQL'
    mutation ActionDiscountCode($basicCodeDiscount: DiscountCodeBasicInput!) {
      discountCodeBasicCreate(basicCodeDiscount: $basicCodeDiscount) {
        codeDiscountNode { id }
        userErrors { field code message }
      }
    }
    GQL;

    public const LOOKUP = <<<'GQL'
    query ActionDiscountByCode($code: String!) {
      codeDiscountNodeByCode(code: $code) {
        id
        codeDiscount { ... on DiscountCodeBasic { title status usageLimit endsAt } }
      }
    }
    GQL;

    public function key(): string
    {
        return 'discount_code';
    }

    public function label(): string
    {
        return 'Issue a discount code';
    }

    public function summary(): string
    {
        return 'Creates a single-use discount code from an approved template (percentage or fixed, capped, expiring).';
    }

    public function requiredScopes(): array
    {
        return [['write_discounts']];
    }

    public function isMoney(): bool
    {
        return true;
    }

    public function riskTier(): string
    {
        return self::RISK_MEDIUM;
    }

    public function replyWaits(): bool
    {
        return true;
    }

    public function paramsHint(): string
    {
        return '{"template": "template key", "value": "optional, at most the template maximum", "customer_specific": true}';
    }

    public static function generateCode(): string
    {
        return strtoupper((string) config('agent_actions.discount_code_prefix', 'SD')).'-'.strtoupper(Str::random(8));
    }

    /** Fields left out of the idempotency hash (the code is random per proposal). */
    public static function idempotencyExclude(): array
    {
        return ['code'];
    }

    public function rules(ActionSettings $settings): array
    {
        $prefix = preg_quote(strtoupper((string) config('agent_actions.discount_code_prefix', 'SD')), '/');

        return [
            'template' => ['required', 'string', 'in:'.implode(',', array_keys($settings->templates()) ?: ['__none__'])],
            'value' => ['nullable', 'numeric', 'gt:0'],
            'customer_specific' => ['nullable', 'boolean'],
            'code' => ['required', 'string', 'regex:/^'.$prefix.'-[A-Z0-9]{8}$/'],
        ];
    }

    protected function normalize(array $params, ActionSettings $settings): array
    {
        $template = $settings->templates()[(string) $params['template']];
        $type = ($template['type'] ?? 'percentage') === 'fixed' ? 'fixed' : 'percentage';
        $value = isset($params['value']) ? (float) $params['value'] : (float) ($template['value'] ?? 0);

        return [
            'code' => (string) $params['code'],
            'customer_specific' => (bool) ($params['customer_specific'] ?? true),
            'template' => (string) $params['template'],
            'type' => $type,
            'value' => $type === 'fixed' ? Money::decimal((int) Money::cents((string) $value)) : round($value, 2),
        ];
    }

    protected function extraErrors(array $params, ActionSettings $settings): array
    {
        $template = $settings->templates()[$params['template']];
        $max = (float) ($template['max_value'] ?? $template['value'] ?? 0);
        $value = (float) $params['value'];
        if ($value <= 0 || $value > $max) {
            return ['value' => ["The value must be above 0 and at most the template maximum ({$max})."]];
        }
        if ($params['type'] === 'percentage' && $value > (float) config('agent_actions.max_discount_percentage', 50)) {
            return ['value' => ['Percentage above the hard maximum.']];
        }

        return [];
    }

    public function amountFromParams(array $params): ?int
    {
        return ($params['type'] ?? null) === 'fixed' ? Money::cents($params['value'] ?? null) : null;
    }

    public function percentage(array $params): ?float
    {
        return ($params['type'] ?? null) === 'percentage' ? (float) $params['value'] : null;
    }

    public function describe(array $params, ?OrderState $state, ActionSettings $settings): string
    {
        $template = $settings->templates()[$params['template'] ?? ''] ?? [];
        $days = $this->expiryDays($template);
        $value = ($params['type'] ?? '') === 'fixed'
            ? Money::format((int) Money::cents($params['value'] ?? '0'), $state?->currency()).' off'
            : ($params['value'] ?? '?').'% off';
        $who = ($params['customer_specific'] ?? true) ? 'only this customer' : 'anyone who has the code';

        return "Create discount code {$params['code']}: {$value} the next order, usable once, by {$who}, expiring in {$days} days"
            .(filled($template['minimum_subtotal'] ?? null) ? ' (minimum spend '.$template['minimum_subtotal'].')' : '')
            .'. The customer gets the code in the reply.';
    }

    public function preconditions(array $params, OrderState $state, ActionContext $ctx): Checks
    {
        $checks = new Checks;
        $checks->currency = $state->currency();
        $checks->amountCents = $this->amountFromParams($params);
        $template = $ctx->settings->templates()[$params['template']] ?? null;
        $checks->check('template', $template !== null, $template !== null ? "Template {$params['template']} exists." : "Template {$params['template']} no longer exists.");
        if (($params['customer_specific'] ?? true)) {
            $checks->check('customer', $state->customerId() !== null, $state->customerId() !== null ? 'The order has a Shopify customer to restrict the code to.' : 'The order has no Shopify customer; the code cannot be limited to them.');
        }

        return $checks;
    }

    public function execute(ShopifyGateway $gateway, array $params, OrderState $state, Checks $checks, ActionContext $ctx): Outcome
    {
        $template = $ctx->settings->templates()[$params['template']];
        $value = $params['type'] === 'fixed'
            ? ['discountAmount' => ['amount' => (string) $params['value'], 'appliesOnEachItem' => false]]
            : ['percentage' => round(((float) $params['value']) / 100, 4)];

        $input = [
            'title' => mb_substr(($template['label'] ?? $params['template']).' - '.$ctx->marker(), 0, 255),
            'code' => $params['code'],
            'startsAt' => now()->toIso8601String(),
            'endsAt' => now()->addDays($this->expiryDays($template))->toIso8601String(),
            'usageLimit' => 1,
            'appliesOncePerCustomer' => true,
            'context' => ($params['customer_specific'] ?? true)
                ? ['customers' => ['add' => [$state->customerId()]]]
                : ['all' => 'ALL'],
            'customerGets' => ['value' => $value, 'items' => ['all' => true]],
        ];
        if (filled($template['minimum_subtotal'] ?? null)) {
            $input['minimumRequirement'] = ['subtotal' => ['greaterThanOrEqualToSubtotal' => Money::decimal((int) Money::cents($template['minimum_subtotal']))]];
        }

        return Outcome::fromResult($gateway->mutate(self::MUTATION, ['basicCodeDiscount' => $input]), 'discountCodeBasicCreate', data: ['code' => $params['code']]);
    }

    public function verify(ShopifyGateway $gateway, array $params, ActionContext $ctx, OrderStateLoader $loader): Outcome
    {
        $result = $gateway->query(self::LOOKUP, ['code' => $params['code']]);
        if (! $result->ok()) {
            return new Outcome(Outcome::UNKNOWN, $result->errorText());
        }
        $node = $result->data['codeDiscountNodeByCode'] ?? null;

        return is_array($node)
            ? new Outcome(Outcome::SUCCEEDED, data: ['discount_node_id' => $node['id'] ?? null, 'code' => $params['code']])
            : new Outcome(Outcome::FAILED, "Discount code {$params['code']} does not exist in Shopify.");
    }

    public function undo(array $params, ?OrderState $state, Outcome $outcome): ?array
    {
        return ['how' => 'Deactivate or delete the discount in Shopify (Discounts).', 'code' => $params['code'] ?? null];
    }

    /** @param  array<string, mixed>  $template */
    private function expiryDays(array $template): int
    {
        return max(1, min((int) ($template['expires_days'] ?? 30), (int) config('agent_actions.max_discount_expiry_days', 90)));
    }
}
