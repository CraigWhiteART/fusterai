test('each auto-send condition blocks on its own', function (array $overrides, array $context, string $blocker) {
    $result = PolicyGate::decide(autoTGate($overrides, $context));

    expect($result['decision'])->toBe(PolicyGate::DRAFT)
        ->and($result['auto_send_eligible'])->toBeFalse()
        ->and($result['auto_send_blockers'])->toBe([$blocker]);
})->with('single blockers');

test('blockers combine and are all reported', function () {
    $result = PolicyGate::decide(autoTGate(
        ['agent_mode' => 'draft', 'proposed_actions' => [['action' => 'refund', 'status' => 'proposed']]],
        ['language' => 'fr', 'daily_remaining' => 0, 'human_replied' => true],
    ));

    expect($result['decision'])->toBe(PolicyGate::DRAFT)
        ->and($result['auto_send_blockers'])->toEqualCanonicalizing(['agent_mode', 'actions_pending', 'language', 'human_replied', 'daily_cap']);
});

test('handover conditions still win over an eligible auto-send', function (array $overrides, string $reason) {
    $result = PolicyGate::decide(autoTGate($overrides));

    expect($result['decision'])->toBe(PolicyGate::HANDOVER)->and($result['reason'])->toBe($reason)->and($result['auto_send_eligible'])->toBeFalse();
})->with([
    'kill switch' => [['kill_switch' => true], 'kill_switch'],
    'risk flag' => [['risk_flags' => ['legal']], 'risk:legal'],
    'always human' => [['playbook' => ['mode' => 'auto', 'rollout_percent' => 100, 'always_human' => true]], 'always_human'],
    'validator failed' => [['validator_passed' => false], 'validation_failed'],
    'validator error' => [['validator_error' => true, 'validator_passed' => false], 'validator_error'],
    'writer handover' => [['writer_handover' => 'needs_human_decision'], 'writer:needs_human_decision'],
]);

test('missing context or missing keys fail closed', function () {
    expect(PolicyGate::decide(autoTGate(['auto_send' => null]))['auto_send_blockers'])->toBe(['no_context']);

    $context = autoTContext();
    unset($context['paused'], $context['human_replied'], $context['daily_remaining']);
    $result = PolicyGate::decide(autoTGate(['auto_send' => $context]));

    expect($result['decision'])->toBe(PolicyGate::DRAFT)
        ->and($result['auto_send_blockers'])->toEqualCanonicalizing(['paused', 'human_replied', 'daily_cap']);

    // Gate inputs outside the context fail closed too: no key = blocked.
    $gate = autoTGate();
    unset($gate['needs_human'], $gate['related_open_conversations']);
    $result = PolicyGate::decide($gate);

    expect($result['decision'])->toBe(PolicyGate::DRAFT)
        ->and($result['auto_send_blockers'])->toBe(['needs_human', 'related_open_conversations']);
});

test('an exception inside the auto-send checks means draft', function () {
    // An object where a string is expected makes the check throw.
    $result = PolicyGate::decide(autoTGate([], ['language' => new stdClass]));

    expect($result['decision'])->toBe(PolicyGate::DRAFT)->and($result['auto_send_blockers'])->toBe(['gate_error']);
});

test('0% rollout never auto-sends and 100% auto-sends every eligible bucket', function () {
    foreach (range(0, 99) as $bucket) {
        $zero = PolicyGate::decide(autoTGate(['rollout_bucket' => $bucket, 'playbook' => ['mode' => 'auto', 'rollout_percent' => 0, 'always_human' => false]]));
        $all = PolicyGate::decide(autoTGate(['rollout_bucket' => $bucket, 'playbook' => ['mode' => 'auto', 'rollout_percent' => 100, 'always_human' => false]]));
        expect($zero['decision'])->toBe(PolicyGate::DRAFT)->and($all['decision'])->toBe(PolicyGate::AUTO_SEND);
    }
});

test('rollout buckets are stable and raising the percentage only adds conversations', function () {
    $ids = range(1, 1000);
    $bucket = fn (int $id) => PolicyGate::rolloutBucket($id);
    $in = fn (int $percent) => array_values(array_filter($ids, fn ($id) => PolicyGate::inRollout($bucket($id), $percent)));

    expect(array_map($bucket, $ids))->toBe(array_map($bucket, $ids));
    foreach ([0, 10, 25, 50, 90, 100] as $i => $percent) {
        $now = $in($percent);
        if ($i > 0) {
            $previous = $in([0, 10, 25, 50, 90, 100][$i - 1]);
            expect(array_diff($previous, $now))->toBe([]); // nobody leaves when it goes up
        }
    }
    expect($in(0))->toBe([])->and($in(100))->toBe($ids)
        ->and(count($in(10)))->toBeGreaterThan(50)->toBeLessThan(150);
});

test('shadow helpers ignore only the workspace mode (and, for candidates, the playbook switch)', function () {
    $shadow = PolicyGate::decide(autoTGate(['agent_mode' => 'shadow'], ['purpose_live' => false]));
    $draftPlaybook = PolicyGate::decide(autoTGate(['agent_mode' => 'shadow', 'playbook' => ['mode' => 'draft', 'rollout_percent' => 0, 'always_human' => false]], ['purpose_live' => false]));
    $angry = PolicyGate::decide(autoTGate(['agent_mode' => 'shadow'], ['purpose_live' => false, 'sentiment' => 'angry']));

    expect(AutoSendContext::wouldAutoSend($shadow))->toBeTrue()
        ->and(AutoSendContext::wouldAutoSend($draftPlaybook))->toBeFalse()
        ->and(AutoSendContext::eligibleIfAuto($draftPlaybook))->toBeTrue()
        ->and(AutoSendContext::wouldAutoSend($angry))->toBeFalse()
        ->and(AutoSendContext::eligibleIfAuto($angry))->toBeFalse();
});
