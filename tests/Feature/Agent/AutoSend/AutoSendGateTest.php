test('every condition holding auto-sends', function () {
    $result = PolicyGate::decide(autoTGate());

    expect($result['decision'])->toBe(PolicyGate::AUTO_SEND)
        ->and($result['auto_send_eligible'])->toBeTrue()
        ->and($result['auto_send_blockers'])->toBe([]);
});

